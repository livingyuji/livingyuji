-- ============================================================================
-- LivingYuji OS — Phase C Showcase visibility support
-- ============================================================================
-- This migration is PREPARED ONLY. Do not apply it until Phases B and A have
-- been reviewed and applied. It does not delete showcase rows.
--
-- Why this exists:
--   The admin Showcase editor already offers "Coming Soon" and "Private"
--   statuses, but the original table constraint rejects them. It also lacks an
--   explicit publication flag for future draft workflows.
--
-- Safety:
--   * Adds columns/constraints and tightens the public read policy only.
--   * Backfills publication as true for existing rows.
--   * Public table reads can only return published, non-Private rows. The
--     server route still applies the same filter in application code.
--   * Does not grant public table access; anonymous requests are limited by
--     the filtered RLS policy below.
-- ============================================================================

BEGIN;

ALTER TABLE public.showcase_projects
  ADD COLUMN IF NOT EXISTS published BOOLEAN NOT NULL DEFAULT true;

-- Replace any existing status CHECK constraint with the full editor status
-- set. The DO block avoids relying on an autogenerated constraint name.
DO $$
DECLARE
  constraint_record RECORD;
BEGIN
  FOR constraint_record IN
    SELECT conname
    FROM pg_constraint
    WHERE conrelid = 'public.showcase_projects'::regclass
      AND contype = 'c'
      AND pg_get_constraintdef(oid) ILIKE '%status%'
  LOOP
    EXECUTE format(
      'ALTER TABLE public.showcase_projects DROP CONSTRAINT %I',
      constraint_record.conname
    );
  END LOOP;
END
$$;

ALTER TABLE public.showcase_projects
  ADD CONSTRAINT showcase_projects_status_check
  CHECK (
    status IN (
      'Released',
      'In Development',
      'Beta',
      'Maintained',
      'Archived',
      'Coming Soon',
      'Private'
    )
  );

CREATE INDEX IF NOT EXISTS idx_showcase_projects_published
  ON public.showcase_projects(published);

-- The original public-read policy exposed every row, including Private and
-- unpublished drafts, to the anon key. Keep public table access readable but
-- filter it at the database boundary as well as in the API route. The status
-- comparison is case-insensitive and ignores surrounding whitespace so a
-- legacy value such as ' private ' cannot leak through the public policy.
DROP POLICY IF EXISTS "Public Read Access for Showcase Projects" ON public.showcase_projects;
DROP POLICY IF EXISTS "Public read published showcase projects" ON public.showcase_projects;
CREATE POLICY "Public read published showcase projects"
  ON public.showcase_projects
  FOR SELECT
  TO anon, authenticated
  USING (published = true AND lower(btrim(status)) <> 'private');

COMMENT ON COLUMN public.showcase_projects.published IS
  'Explicit publication flag. Public RLS also hides Private status rows using a case-insensitive comparison.';

COMMIT;
